data class PredictionResult(
    val riskLevel: RiskLevel,
    val confidence: Double,
    val votes: List<Int>,
    val classProbabilities: List<Double>,
    val features: DoubleArray
) {
    val confidencePercent: Int get() = (confidence * 100).toInt()

    fun topFeaturesByImportance(): List<Pair<String, Double>> {
        return AirQualityClassifier.FEATURE_NAMES.zip(AirQualityClassifier.FEATURE_IMPORTANCE.toList())
            .sortedByDescending { it.second }
            .take(4)
    }
}
