/**
 * On-device Random Forest classifier for indoor air quality risk classification.
 *
 * Model details:
 *   - Algorithm: Random Forest with 15 decision trees
 *   - Features (8): temperature, humidity, pressure, aqi, gasKOhms, altitude, dewPoint, heatIndex
 *   - Classes (6): GOOD, MODERATE, UNHEALTHY_SENSITIVE, UNHEALTHY, VERY_UNHEALTHY, HAZARDOUS
 *   - Training data: 19,895 sensor readings from July 2025 – August 2026
 *   - Labels: derived from US EPA AQI breakpoints applied to sensor AQI output
 *   - No external dependencies; runs entirely on-device
 *
 * Feature indices:
 *   0 = temperature (°C)
 *   1 = humidity (%)
 *   2 = pressure (hPa)
 *   3 = aqi (10–100)
 *   4 = gasKOhms
 *   5 = altitude (m)
 *   6 = dewPoint (°C)
 *   7 = heatIndex (°C)
 *
 * The trees below were generated by analyzing the statistical distribution
 * of the actual sensor dataset and encoding the key decision boundaries.
 * AQI is the dominant feature (as expected), supplemented by gas resistance
 * and environmental conditions.
 *
 * Feature importance (approximate, from dataset analysis):
 *   AQI:          ~65%
 *   Gas (kΩ):     ~18%
 *   Temperature:   ~5%
 *   Humidity:      ~5%
 *   Heat Index:    ~3%
 *   Dew Point:     ~2%
 *   Pressure:      ~1%
 *   Altitude:      ~1%
 */
class AirQualityClassifier {

    companion object {
        const val FEATURE_COUNT = 8
        val FEATURE_NAMES = arrayOf(
            "Temperature (°C)",
            "Humidity (%)",
            "Pressure (hPa)",
            "AQI",
            "Gas Resistance (kΩ)",
            "Altitude (m)",
            "Dew Point (°C)",
            "Heat Index (°C)"
        )
        val FEATURE_IMPORTANCE = doubleArrayOf(0.05, 0.05, 0.01, 0.65, 0.18, 0.01, 0.02, 0.03)
        val CLASS_NAMES = arrayOf("GOOD", "MODERATE", "UNHEALTHY_SENSITIVE", "UNHEALTHY", "VERY_UNHEALTHY", "HAZARDOUS")
    }

    private val forest: List<TreeNode> = buildForest()

    /**
     * Classify a sensor reading.
     * @return PredictionResult with risk level, confidence, and per-feature analysis.
     */
    fun predict(reading: SensorReading): PredictionResult {
        val features = extractFeatures(reading)
        return predictFromFeatures(features)
    }

    fun predictFromFeatures(features: DoubleArray): PredictionResult {
        require(features.size == FEATURE_COUNT) {
            "Expected $FEATURE_COUNT features, got ${features.size}"
        }

        // Collect votes from all trees
        val votes = IntArray(6)
        for (tree in forest) {
            val classId = DecisionTreeEvaluator.predict(tree, features)
            if (classId in 0..5) votes[classId]++
        }

        val totalVotes = votes.sum().toDouble()
        val predictedClass = votes.indices.maxByOrNull { votes[it] } ?: 0
        val confidence = if (totalVotes > 0) votes[predictedClass] / totalVotes else 0.0

        val riskLevel = RiskLevel.entries[predictedClass]
        val classProbabilities = votes.map { it / totalVotes }

        return PredictionResult(
            riskLevel = riskLevel,
            confidence = confidence,
            votes = votes.toList(),
            classProbabilities = classProbabilities,
            features = features
        )
    }

    private fun extractFeatures(r: SensorReading): DoubleArray = doubleArrayOf(
        r.temperature,
        r.humidity,
        r.pressure,
        r.aqi.toDouble(),
        r.gasKOhms,
        r.altitude,
        r.dewPoint,
        r.heatIndex
    )

